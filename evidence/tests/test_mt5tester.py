def test_mt5_value_str_formats():
    assert mt5_value_str(True) == "true"
    assert mt5_value_str(False) == "false"
    assert mt5_value_str(0) == "0"
    assert mt5_value_str(20240904) == "20240904"
    assert mt5_value_str(1.0) == "1.0"
    assert mt5_value_str(10.0) == "10.0"
    assert mt5_value_str(2.5) == "2.5"
    assert mt5_value_str(0.01) == "0.01"
    assert mt5_value_str("x=1") == "x=1"


def test_parse_set_roundtrip_real_preset():
    text = ("; mql5bot preset\n"
            "InpStrategy=0\n"
            "InpSlAtr=2.5\n"
            "InpAllowShort=true\n")
    lines = parse_set(text)
    assert [ln.key for ln in lines] == ["InpStrategy", "InpSlAtr", "InpAllowShort"]
    assert render_set(lines) == ("InpStrategy=0\n"
                                 "InpSlAtr=2.5\n"
                                 "InpAllowShort=true\n")


def test_parse_set_preserves_optimization_ranges():
    text = ("StopLoss=50||50||1||200||N\n"
            "TakeProfit=100||100||1||500||Y\n"
            "UseFilter=true\n")
    lines = parse_set(text)
    assert lines[0].value == "50"
    assert lines[0].opt_range == "||50||1||200||N"
    assert lines[1].opt_range == "||100||1||500||Y"
    assert lines[2].opt_range is None
    assert render_set(lines) == text


def test_parse_set_drops_comments_and_blanks():
    lines = parse_set("; comment\n\nInpMagic=1\n; tail\n")
    assert len(lines) == 1 and lines[0].key == "InpMagic"


def test_validate_inputs_rejects_unknown():
    with pytest.raises(ValueError, match="unknown EA input"):
        validate_inputs({"InpStrategy": 0, "InpNotReal": 1},
                        known=set(EA_INPUT_DEFAULTS))
    validate_inputs({"InpStrategy": 0}, known=set(EA_INPUT_DEFAULTS))
    validate_inputs({"Anything": 1}, known=None)  # third-party EA passthrough


def test_inputs_to_lines_renders_all_defaults():
    lines = inputs_to_lines(dict(EA_INPUT_DEFAULTS))
    assert len(lines) == len(EA_INPUT_DEFAULTS)
    by_key = {ln.key: ln.value for ln in lines}
    assert by_key["InpAllowShort"] == "true"
    assert by_key["InpStrategy"] == "0"
    assert by_key["InpRiskPercent"] == "1.0"


