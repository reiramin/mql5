def test_parse_report_html_missing_rows_are_none_and_script_ignored():
    html = ("<html><table>"
            "<tr><td>Total Net Profit</td><td>5.00</td></tr>"
            "</table>"
            "<script>var x = '<tr><td>Total Net Profit</td><td>999</td></tr>';</script>"
            "</html>")
    rep = parse_report_html(html)
    assert rep.metrics["total_net_profit"] == 5.0
    assert rep.metrics["gross_profit"] is None
    assert rep.metrics["sharpe_ratio"] is None
    assert len(rep.fields) == 1


def test_parse_report_html_old_style_drawdown_labels():
    html = ("<html><table>"
            "<tr><td>Absolute Drawdown</td><td>405.00</td></tr>"
            "<tr><td>Maximal Drawdown</td><td>949.00 (10.79%)</td></tr>"
            "<tr><td>Relative Drawdown</td><td>10.93% (756.00)</td></tr>"
            "</table></html>")
    m = parse_report_html(html).metrics
    assert m["balance_drawdown_absolute"] == 405.0
    assert m["balance_drawdown_maximal"] == {"money": 949.0, "pct": 10.79}
    assert m["balance_drawdown_relative"] == {"pct": 10.93, "money": 756.0}


def test_parse_report_html_case_and_whitespace_tolerance():
    html = ("<html><table>"
            "<tr><td>  total&nbsp;&nbsp;NET&nbsp;profit </td><td> 42.50 </td></tr>"
            "</table></html>")
    rep = parse_report_html(html)
    assert rep.metrics["total_net_profit"] == 42.5
    # raw label kept verbatim (cleaned) in fields
    assert "total NET profit" in rep.fields


