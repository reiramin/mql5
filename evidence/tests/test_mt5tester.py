def test_tester_config_defaults_valid():
    cfg = MT5TesterConfig()
    cfg.validate()
    assert cfg.timeframe in MT5_TIMEFRAMES
    assert cfg.model in MT5_MODEL_LABELS


@pytest.mark.parametrize("field,value,match", [
    ("timeframe", "H2", "timeframe"),
    ("model", 9, "model"),
    ("date_from", "2024/01/01", "YYYY.MM.DD"),
    ("date_from", "2025.01.01", "after"),  # later than the default date_to
    ("deposit", 0.0, "deposit"),
    ("currency", "US", "3-letter"),
    ("leverage", 0, "leverage"),
    ("ea", "Mql5Bot.mq5", ".ex5"),
])
def test_tester_config_rejects_bad_values(field, value, match):
    cfg = MT5TesterConfig()
    setattr(cfg, field, value)
    with pytest.raises(ValueError, match=match):
        cfg.validate()


def test_render_ini_golden():
    cfg = MT5TesterConfig(ea="Experts\\Mql5Bot\\Mql5Bot.ex5",
                       symbol="EURUSD", timeframe="H1", model=1,
                       date_from="2023.01.01", date_to="2024.01.01",
                       deposit=10000.0, currency="USD", leverage=100,
                       inputs={"InpStrategy": 0, "InpSlAtr": 2.5,
                               "InpAllowShort": True})
    ini = cfg.render_ini()
    assert ini.startswith("; generated by")
    assert "[Tester]" in ini and "[TesterInputs]" in ini
    assert ini.index("[Tester]") < ini.index("[TesterInputs]")
    for expected in ("Expert=Experts\\Mql5Bot\\Mql5Bot.ex5",
                     "Symbol=EURUSD", "Period=H1", "Model=1",
                     "Optimization=0", "FromDate=2023.01.01",
                     "ToDate=2024.01.01", "Deposit=10000.00",
                     "Currency=USD", "Leverage=100",
                     "ShutdownTerminal=1", "ReplaceReport=1",
                     "InpStrategy=0", "InpSlAtr=2.5", "InpAllowShort=true"):
        assert expected in ini, expected


def test_safe_report_name_deterministic_and_sanitized():
    a = MT5TesterConfig(symbol="XAUUSD", timeframe="H4",
                     date_from="2020.01.01", date_to="2021.06.30")
    b = MT5TesterConfig(symbol="XAUUSD", timeframe="H4",
                     date_from="2020.01.01", date_to="2021.06.30")
    assert a.safe_report_name == b.safe_report_name == "XAUUSD_H4_20200101_20210630"
    custom = MT5TesterConfig(report_name="My EA:run #1")
    assert custom.safe_report_name == "My_EA_run_1"
    with pytest.raises(ValueError, match="not usable"):
        _ = MT5TesterConfig(report_name="///").safe_report_name


