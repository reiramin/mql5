    for rel, src in ((og.symbolspec_import_rel("gold2"),
                      ev / "import_EURUSD.G2.json"),
                     (og.tester_ini_rel("gold2", "m1_ohlc"),
                      ev / "tester_gold2_m1_ohlc.ini")):
        assert (pkg / rel).read_bytes() == src.read_bytes()
        man = json.loads((pkg / og.LAYOUT["archive_manifest"]).read_text())
