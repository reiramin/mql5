def _import_record(readback="1.0000000000", ok=True):
    return {"ok": True, "symbol": "EURUSD.G2", "verified_properties": [
        {"enum": "SYMBOL_TRADE_CONTRACT_SIZE", "expected": "100000.0000000000",
         "ok": True, "readback": "100000.0000000000"},
        {"enum": "SYMBOL_TRADE_TICK_VALUE", "expected": "1.0000000000",
         "ok": ok, "readback": readback}]}


def _ini(currency="USD"):
    return ("; generated by mql5bot.mt5tester\n[Tester]\n"
            "Expert=Mql5Bot\\Mql5Bot.ex5\nSymbol=EURUSD.G2\nPeriod=M1\n"
            f"Deposit=10000.00\nCurrency={currency}\nLeverage=100\n"
            "\n[TesterInputs]\nInpBaseGateWeight=1.0\n")


def _pkg(tmp_path, export, record=None, inis=None, bind=True):
    root = tmp_path / "pkg"
    (root / "symbolspec").mkdir(parents=True)
    (root / og.LAYOUT["symbolspec"]).write_text(json.dumps(export))
    if record is not None:
        (root / og.symbolspec_import_rel("gold2")).write_text(
            json.dumps(record))
    for model, text in (inis or {}).items():
        p = root / og.tester_ini_rel("gold2", model)
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(text)
    if bind:
        arts = {str(p.relative_to(root)).replace("\\", "/"):
                hashlib.sha256(p.read_bytes()).hexdigest()
                for p in sorted(root.rglob("*")) if p.is_file()}
        (root / og.LAYOUT["archive_manifest"]).write_text(
            json.dumps({"artifacts": arts}))
    return root


def _witnessed(tmp_path, export=CUSTOM_EXPORT, **kw):
    record = kw.pop("record", _import_record())
    inis = kw.pop("inis", {"m1_ohlc": _ini(), "every_tick": _ini()})
    return _pkg(tmp_path, export, record, inis, **kw)


