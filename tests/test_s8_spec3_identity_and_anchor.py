# ------------------------------------------------ 6. S8-ANCHOR-REL-1

def _git(repo: Path, *args: str) -> str:
    return subprocess.run(["git", "-C", str(repo), *args], check=True,
                          capture_output=True, text=True).stdout.strip()


@pytest.fixture()
def anchored(tmp_path):
    """A throwaway repo: the frozen files at the anchor, a descendant that
    changes only an unfrozen file, and the frozen record pinning them."""
    repo = tmp_path / "repo"
    repo.mkdir()
    _git(repo, "init", "-q")
    _git(repo, "config", "user.email", "t@example.invalid")
    _git(repo, "config", "user.name", "t")
    _git(repo, "config", "commit.gpgsign", "false")
    files = {"artifacts/gold/gold_fixture.csv": "a\n",
             "artifacts/gold/manifest.json": "{}\n",
             "artifacts/gold_2/gold2_fixture.csv": "b\n",
             "artifacts/gold_2/reconciliation.json": "[]\n",
             "README": "x\n"}
    for rel, text in files.items():
        (repo / rel).parent.mkdir(parents=True, exist_ok=True)
        (repo / rel).write_text(text)
    _git(repo, "add", "-A")
    _git(repo, "commit", "-qm", "anchor")
    anchor = _git(repo, "rev-parse", "HEAD")

    def sha(rel):
        return hashlib.sha256((repo / rel).read_bytes()).hexdigest()
    frozen = {"source": {"commit": anchor},
              "gold_1": {"fixture_sha256": sha("artifacts/gold/gold_fixture.csv"),
                         "manifest_sha256": sha("artifacts/gold/manifest.json")},
              "gold_2": {"fixture_sha256": sha("artifacts/gold_2/gold2_fixture.csv"),
                         "artifact_hash_chain": {
                             "reconciliation.json":
                                 sha("artifacts/gold_2/reconciliation.json")}}}
    (repo / "README").write_text("y\n")
    _git(repo, "commit", "-qam", "descendant")
    return repo, anchor, _git(repo, "rev-parse", "HEAD"), frozen


def test_anchor_itself_is_exact(anchored):
    repo, anchor, _, frozen = anchored
    rel = og.anchor_relation(repo, anchor, anchor, frozen)
    assert rel["relation"] == og.ANCHOR_RELATION_EXACT


def test_descendant_with_identical_frozen_bytes_is_accepted(anchored):
    repo, anchor, head, frozen = anchored
    rel = og.anchor_relation(repo, anchor, head, frozen)
    assert rel["relation"] == og.ANCHOR_RELATION_DESCENDANT, rel["reasons"]
    assert len(rel["frozen_files"]) == 4
    assert all(v["pin"] == v["at_commit"]
               for v in rel["frozen_files"].values())
    acc = og.source_commit_relation(
        head, anchor, lambda c: og.anchor_relation(repo, anchor, c, frozen))
    assert acc["accepted"] is True
    assert acc["relation"] == "DESCENDANT_FROZEN_BYTES_IDENTICAL"


def test_descendant_that_changed_a_frozen_file_is_refused(anchored):
    repo, anchor, _, frozen = anchored
    (repo / "artifacts/gold_2/reconciliation.json").write_text("[1]\n")
    _git(repo, "commit", "-qam", "edit a frozen file")
    head = _git(repo, "rev-parse", "HEAD")
    rel = og.anchor_relation(repo, anchor, head, frozen)
    assert rel["relation"] is None
    assert any("reconciliation.json sha256" in r for r in rel["reasons"])


def test_working_tree_bytes_are_not_what_is_judged(anchored):
    """The verifier hashes the bytes AT the recorded commit (git show); a
    restored working-tree file cannot launder a committed change."""
    repo, anchor, _, frozen = anchored
    p = repo / "artifacts/gold/manifest.json"
    p.write_text('{"x": 1}\n')
    _git(repo, "commit", "-qam", "edit frozen manifest")
    head = _git(repo, "rev-parse", "HEAD")
    p.write_text("{}\n")                       # restored, uncommitted
    assert og.anchor_relation(repo, anchor, head, frozen)["relation"] is None


def test_older_diverged_unknown_and_short_commits_are_refused(anchored):
    repo, anchor, head, frozen = anchored
    # older: the recorded commit is an ANCESTOR of the anchor
    _git(repo, "checkout", "-q", anchor)
    older_frozen = dict(frozen, source={"commit": head})
    assert og.anchor_relation(repo, head, anchor, older_frozen)[
        "relation"] is None
    # diverged: a sibling of the descendant
    _git(repo, "checkout", "-qb", "side", anchor + "~0")
    (repo / "README").write_text("z\n")
    _git(repo, "commit", "-qam", "sibling")
    sib = _git(repo, "rev-parse", "HEAD")
    assert og.anchor_relation(repo, head, sib, frozen)["relation"] is None
    # unknown commit, short SHA, no repository
    unknown = og.anchor_relation(repo, anchor, "f" * 40, frozen)
    assert unknown["relation"] is None
    assert "not a commit in this repository" in unknown["reasons"][0]
    assert og.anchor_relation(repo, anchor, head[:12], frozen)[
        "relation"] is None
    assert og.anchor_relation(None, anchor, head, frozen)["relation"] is None
    # no repository bound: only equality
    assert og.source_commit_relation(head, anchor)["accepted"] is False


def test_verify_compile_accepts_only_through_the_relation(tmp_path,
                                                          anchored):
    repo, anchor, head, frozen = anchored
    root = tmp_path / "pkg"
    (root / "compile").mkdir(parents=True)
    (root / og.LAYOUT["compile_log"]).write_text("0 errors, 0 warnings\n")
    (root / og.LAYOUT["ex5"]).write_bytes(b"ex5")
    meta = {"SOURCE_COMMIT": head, "COMPILER_VERSION": "5", "TERMINAL_BUILD":
            5430, "EX5_SHA256": og.sha256_file(root / og.LAYOUT["ex5"]),
            "COMPILE_TIMESTAMP": "2026-10-05T00:00:00Z",
            "COMPILER_LOG_SHA256": og.sha256_file(
                root / og.LAYOUT["compile_log"]),
            "ERRORS": 0, "WARNINGS": 0}
    (root / og.LAYOUT["compile_metadata"]).write_text(json.dumps(meta))
    plain = og.verify_compile(root, anchor)
    assert plain["checks"]["source_commit"] == og.MISMATCHED
    rel = og.verify_compile(
        root, anchor, lambda c: og.anchor_relation(repo, anchor, c, frozen))
    assert rel["checks"]["source_commit"] == "VALID"
    assert rel["source_commit_relation"]["relation"] == \
        og.ANCHOR_RELATION_DESCENDANT


